UError_t NCO_Create(NCO_t* nco) {
  UError_t err = uSuccess;

  if (uSuccess == err) {
    if (NULL == nco) {
      err = uFailure;
    }
  }

  if (uSuccess == err) {
    nco->offset = 0u;
    nco->weight = 0u;
    nco->wtable = i8sin;
  }

  return err;
}
